import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

/** Read every exported name from a module, classifying type vs value. */
function exportsOf(file) {
  const src = readFileSync(file, 'utf8');
  const names = new Set();
  for (const m of src.matchAll(
    /^export\s+(?:declare\s+)?(?:async\s+)?(type|interface|const|let|function|class|enum)\s+([A-Za-z0-9_]+)/gm,
  )) {
    names.add(`${m[1]}|${m[2]}`);
  }
  for (const m of src.matchAll(/^export\s*\{([^}]*)\}/gm)) {
    for (const part of m[1].split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop()?.trim();
      if (name && /^[A-Za-z0-9_]+$/.test(name)) names.add(`reexport|${name}`);
    }
  }
  return names;
}

const dir = 'src/features';
const files = readdirSync(dir).filter((f) => f.endsWith('.ts') && f !== 'index.ts');

const byModule = new Map();
for (const f of files) byModule.set(f.replace('.ts', ''), exportsOf(`${dir}/${f}`));

// Flatten, detecting every name claimed by more than one module.
const claims = new Map();
for (const [mod, names] of byModule) {
  for (const entry of names) {
    const name = entry.split('|')[1];
    if (!claims.has(name)) claims.set(name, []);
    claims.get(name).push(mod);
  }
}

const taken = new Set();
const lines = [];
lines.push(`/**
 * Nyx-Baileys — features barrel.
 *
 * ## Why this is a separate entry point
 *
 * These modules predate the toolkit and duplicate ~42 of its names
 * (\`formatDuration\`, \`archiveChat\`, \`createGroup\`, \`RateLimiter\`, …). Flattening
 * both into one barrel produces ambiguous re-exports TypeScript refuses to
 * resolve, and renaming 42 functions to force a merge makes the worse API the
 * surviving one.
 *
 * So they ship under their own subpath: \`nyx-baileys/features\`. Both APIs stay
 * reachable, nothing is renamed, and the caller chooses.
 *
 * ## Generated
 *
 * This barrel is generated by \`scripts/build-features-barrel.mjs\` from what the
 * modules actually export. Names claimed by more than one module are aliased
 * with the module name as a prefix rather than silently resolved — four of them
 * (\`Alert\`, \`HealthStatus\`, \`DashboardSnapshot\`, \`MetricPoint\`) are declared with
 * **incompatible shapes**, and picking a winner would break the other in a way
 * the type system cannot explain.
 *
 * **Nothing in here has run against a real WhatsApp session.** These are
 * utilities: they shape payloads and read metadata. Whether a shaped payload
 * *renders* is the separate, hardware-verified question tracked in
 * \`docs/VERIFICATION.md\`.
 */
`);

for (const [mod, names] of [...byModule].sort()) {
  const sorted = [...names].sort((a, b) => a.split('|')[1].localeCompare(b.split('|')[1]));
  const values = sorted.filter((n) => !n.startsWith('type|') && !n.startsWith('interface|'));
  const types = sorted.filter((n) => n.startsWith('type|') || n.startsWith('interface|'));

  const aliased = [];
  const plain = [];
  for (const entry of values) {
    const name = entry.split('|')[1];
    if (claims.get(name).length > 1) aliased.push(name);
    else plain.push(name);
  }

  // Types collide exactly like values do. `HealthStatus` is a type in BOTH
  // analytics and observability with different unions, so re-exporting it
  // un-aliased twice is TS2300 — not a warning TypeScript resolves, a hard error.
  const aliasedTypes = [];
  const plainTypes = [];
  for (const entry of types) {
    const name = entry.split('|')[1];
    if (claims.get(name).length > 1) aliasedTypes.push(name);
    else plainTypes.push(name);
  }

  if (plain.length || plainTypes.length) {
    lines.push(`export {\n${plain.map((n) => `  ${n},`).join('\n')}\n} from './${mod}.js';`);
  }
  if (plainTypes.length) {
    lines.push(`export type {\n${plainTypes.map((n) => `  ${n},`).join('\n')}\n} from './${mod}.js';`);
  }
  if (aliased.length || aliasedTypes.length) {
    lines.push(
      `/* ${mod} shares these names with another module. Aliased rather than merged:\n`
      + `   whichever loaded first would otherwise win silently. */\n`
      + `export {\n${[...aliased, ...aliasedTypes]
        .map((n) => `  ${n} as ${mod}${n[0].toUpperCase()}${n.slice(1)},`)
        .join('\n')}\n} from './${mod}.js';`,
    );
  }
  lines.push('');
}

writeFileSync(`${dir}/index.ts`, lines.join('\n'));
console.log(`barrel written: ${byModule.size} modules, ${[...claims.values()].filter((v) => v.length > 1).length} shared names aliased`);